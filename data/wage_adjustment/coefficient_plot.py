def load_main(fd_suffix):
    """
    Load model_summary_table{fd_suffix}.csv.
    Returns (co_df, io_df) each with columns: label, Coef, SE, p-value.
    """
    path = f"{cache_prefix}model_summary_table{fd_suffix}.csv"
    df   = pd.read_csv(path)

    co = df[df["Panel type"] == "Company-Occ"].copy()
    co["label"] = co["SOC level"].str.replace("SOC_", "SOC-", regex=False)
    co = co.sort_values("SOC level").reset_index(drop=True)

    io = df[df["Panel type"] == "Industry-Occ"].copy()
    io["label"] = (
        io["NAICS level"] + " x " +
        io["SOC level"].str.replace("SOC_", "SOC-", regex=False)
    )
    io = io.sort_values(["NAICS level", "SOC level"]).reset_index(drop=True)

    for d in (co, io):
        d.rename(columns={"Coef (months)": "Coef"}, inplace=True)

    return co, io


