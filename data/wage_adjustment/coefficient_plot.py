# HELPER: load and prepare cross-section data
# ===========================================================================
def load_cross_section():
    """
    Reads coefs_cross_section_months.csv and selects the most-saturated model
    from each of the four estimation groups (Base, IDW, No-YM, No-YM IDW).
    The most-saturated model is the last row within each group prefix after
    filtering to the duration_months coefficient.
    """
    #cs_df = pd.read_csv(f"{cache_prefix}coefs_cross_section.csv")
    cs_df = pd.read_csv(f"{cache_prefix}coefs_cross_section_months.csv")
    cs_df = cs_df[cs_df["variable"] == "duration_months"].copy()

    # Group prefixes generated by the regression script
    groups = {
        "Months":           "Base |",
        "Months (IDW)":     "IDW |",
        "Months no-YM":     "No-YM |",
        "Months IDW no-YM": "No-YM IDW |",
    }

    rows = []
    for label, prefix in groups.items():
        # "No-YM |" must not match "No-YM IDW |"
        if prefix == "No-YM |":
            mask = cs_df["model"].str.startswith(prefix) & \
                   ~cs_df["model"].str.startswith("No-YM IDW |")
        else:
            mask = cs_df["model"].str.startswith(prefix)

        subset = cs_df[mask]
        if subset.empty:
            continue
        # Most saturated = last spec in the group
        row = subset.iloc[-1]
        rows.append({
            "label": label,
            "coef":  row["coef"],
            "se":    row["se"],
            "pval":  row["pvalue"],
        })

    return pd.DataFrame(rows)


# ===========================================================================
# HELPER: load panel summary data for one estimator
# ===========================================================================
def load_panel_summary(fd_suffix):
    path = f"{cache_prefix}model_summary_table{fd_suffix}.csv"
    summary = pd.read_csv(path)

    # --- Company-Occ ---
    co = summary[summary["Panel type"] == "Company-Occ"].copy()
    co["label"] = co["SOC level"].str.replace("SOC_", "SOC-", regex=False)
    co = co.sort_values("SOC level").reset_index(drop=True)

    # --- Industry-Occ ---
    io = summary[summary["Panel type"] == "Industry-Occ"].copy()
    io["label"] = (
        io["NAICS level"] + " × " +
        io["SOC level"].str.replace("SOC_", "SOC-", regex=False)
    )
    io = io.sort_values(["NAICS level", "SOC level"]).reset_index(drop=True)

    return co, io


