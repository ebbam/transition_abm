# ===========================================================================
# HELPER: draw one coefficient panel onto an axis
# ===========================================================================
def plot_panel(ax, labels, coefs, ses, pvals, title):
    """
    Scatter-plot coefficients with 95 % CI error bars.
    Significant estimates: filled marker, solid error bar (COL_SIG).
    Insignificant:         open marker,  dashed error bar (COL_INSIG).
    """
    x = np.arange(len(labels))

    for i, (c, s, p) in enumerate(zip(coefs, ses, pvals)):
        sig = p < ALPHA
        col = COL_SIG   if sig else COL_INSIG
        mfc = col       if sig else "white"
        ls  = "solid"   if sig else "dashed"

        ax.errorbar(
            i, c, yerr=1.96 * s,
            fmt="o",
            color=col, markerfacecolor=mfc, markeredgecolor=col,
            ecolor=col, elinewidth=1.2, capsize=3,
            markersize=6, linestyle=ls,
        )

    ax.axhline(0, color="black", linewidth=0.6, linestyle=":")
    ax.set_xticks(x)
    # Small, fixed tick-label size is a deliberate content-density exception
    # (up to ~20 labels in the Industry-Occ panel at TEXTWIDTH) -- same
    # convention as dense heatmap/group tick labels elsewhere in the project,
    # not an arbitrary override of the shared rcParams size.
    ax.set_xticklabels(labels, rotation=45, ha="right", fontsize=7)
    ax.set_title(title, fontweight="bold")
    ax.set_xlim(-0.6, len(labels) - 0.4)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)


