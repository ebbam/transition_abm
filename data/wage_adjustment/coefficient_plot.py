def plot_panel(ax, labels, coefs, ses, pvals, title, xlabel=None):
    """
    Scatter-plot coefficients with 95% CI error bars.
    Significant:   filled marker, solid error bar (COL_SIG).
    Insignificant: open marker,  dashed error bar (COL_INSIG).
    """
    x = np.arange(len(labels))

    for i, (c, s, p) in enumerate(zip(coefs, ses, pvals)):
        if not np.isfinite(c) or not np.isfinite(s):
            continue
        sig = p < ALPHA
        col = COL_SIG   if sig else COL_INSIG
        mfc = col       if sig else "white"
        ls  = "solid"   if sig else "dashed"

        ax.errorbar(
            i, c, yerr=1.96 * s,
            fmt="o",
            color=col, markerfacecolor=mfc, markeredgecolor=col,
            ecolor=col, elinewidth=1.2, capsize=3,
            markersize=5, linestyle=ls,
        )

    ax.axhline(0, color="black", linewidth=0.6, linestyle=":")

    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=45, ha="right", fontsize=6.5)
    ax.set_title(title, fontweight="bold", fontsize=9)
    ax.set_xlim(-0.6, len(labels) - 0.4)
    if xlabel:
        ax.set_xlabel(xlabel, fontsize=8)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)


